async function main() {
  console.log('Seeding initial items into database...');
  const d = getDrizzle();

  // Find tenant
  const [t] = await d.select().from(schema.tenants).where(eq(schema.tenants.code, TENANT_CODE));
  if (!t) {
    console.error(`Tenant ${TENANT_CODE} not found!`);
    process.exit(1);
  }

  console.log(`Using tenant: ${t.name} (${t.id})`);

  // Bypass RLS in session for admin seeding
  await pool.query(`SET app.tenant_id = '${t.id}'`);

  let count = 0;
  for (const item of SEED_ITEMS) {
    const existing = await d
      .select({ id: schema.items.id })
      .from(schema.items)
      .where(eq(schema.items.code, item.code))
      .limit(1);

    if (existing.length === 0) {
      await d.insert(schema.items).values({
        ...item,
        tenantId: t.id,
        stock: String(item.stock ?? 0),
        minStock: String(item.min_stock ?? 0),
        maxStock: String(item.max_stock ?? 0),
        reorderPoint: String(item.reorder_point ?? 0),
        cost: String(item.cost ?? 0),
        sellingPrice: String(item.selling_price ?? 0),
        partWeightGrams: String(item.part_weight_grams ?? 0),
        runnerWeightGrams: String(item.runner_weight_grams ?? 0),
        cycleTime: String(item.cycle_time ?? 0),
        cycleTimeSeconds: String(item.cycle_time_seconds ?? 0),
      } as any);
      count++;
      console.log(`  + Seeded item: ${item.code} (${item.name})`);
    } else {
      console.log(`  = Exists: ${item.code}`);
    }
  }

  console.log(`\n✅ Finished seeding ${count} items.`);
  await pool.end();
}

main().catch((err) => {
  console.error('Seed error:', err);
  process.exit(1);
});
