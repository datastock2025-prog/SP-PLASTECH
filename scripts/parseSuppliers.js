function mapCategory(class1, name) {
  const c = (class1 || '').toUpperCase();
  const n = (name || '').toUpperCase();

  if (c.includes('RAW MATERIAL') || c.includes('RAW MATERIALS') || c.includes('POLYMER') || c.includes('RESIN') || n.includes('POLYMER') || n.includes('PLAST') || n.includes('PETROCHEM') || n.includes('CHEMICAL')) {
    return 'Virgin Resin';
  }
  if (c.includes('PACKING') || c.includes('CARTON') || c.includes('BAG') || n.includes('PACK') || n.includes('CARTON')) {
    return 'Packaging Materials';
  }
  if (c.includes('CONSUMABLE') || c.includes('ELECTRICAL') || c.includes('OIL') || c.includes('LUBRIC') || c.includes('PAINT') || c.includes('HARDWARE') || c.includes('GAS') || c.includes('COTTON') || c.includes('LABEL')) {
    return 'Consumables & Lubricants';
  }
  if (c.includes('MOLD') || n.includes('MOLD') || n.includes('MOULD') || n.includes('TOOL') || n.includes('DIE')) {
    return 'Molds & Tooling';
  }
  if (c.includes('ASSET') || c.includes('MACHIN') || c.includes('MAINT') || c.includes('SPARE') || n.includes('MACHINERY') || n.includes('ENGINEERING')) {
    return 'Machine Spare Parts';
  }
  if (c.includes('INSTRUMENT') || c.includes('CALIBRATION') || c.includes('TESTING') || c.includes('LABORAT') || c.includes('MEASUREMENT')) {
    return 'Testing & Calibration Services';
  }
  if (c.includes('JOB WORK') || c.includes('SERVICE') || c.includes('LOGISTIC') || c.includes('TRANSPORT') || c.includes('CATERING')) {
    return 'Subcontracting Services';
  }
  if (c.includes('BOB') || c.includes('RUBBER') || c.includes('FASTENER') || c.includes('SPRING')) {
    return 'Additives & Fillers';
  }
  return 'Virgin Resin';
}

function mapSupplierType(category, name) {
  const n = (name || '').toUpperCase();
  if (category === 'Subcontracting Services') return 'Subcontractor';
  if (category === 'Testing & Calibration Services') return 'Service Provider';
  if (n.includes('TRAD') || n.includes('COMMERCIAL') || n.includes('AGENC') || n.includes('ENTERPRISE') || n.includes('STORE') || n.includes('SUPPLIER')) {
    return 'Authorized Distributor';
  }
  if (n.includes('LIMITED') || n.includes('PVT LTD') || n.includes('INDUSTRIES') || n.includes('POLYMER') || n.includes('MFG') || n.includes('MANUFACTURING')) {
    return 'Manufacturer';
  }
  return 'Authorized Distributor';
}

function extractGstin(regNo) {
  if (!regNo) return '';
  const match = regNo.match(/([0-9]{2}[A-Z]{5}[0-9]{4}[A-Z]{1}[1-9A-Z]{1}Z[0-9A-Z]{1})/i);
  return match ? match[1].toUpperCase() : regNo.replace(/^GSTIN\s*:\s*/i, '').trim();
}

function extractPan(regNo, gstin) {
  if (gstin && gstin.length >= 12) {
    return gstin.substring(2, 12).toUpperCase();
  }
  if (!regNo) return '';
  const match = regNo.match(/PAN\s*[-:]\s*([A-Z]{5}[0-9]{4}[A-Z]{1})/i);
  return match ? match[1].toUpperCase() : '';
}

